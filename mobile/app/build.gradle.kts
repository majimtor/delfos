// Where the application talks to. The APK on Releases talks to the public API; a build against a
// local stack passes `-Pdelfos.apiBaseUrl=http://10.0.2.2:8080/api/v1` (the emulator's host).
val apiBaseUrl = providers.gradleProperty("delfos.apiBaseUrl").getOrElse("https://api.delfos.manuelalejandro.com/api/v1")
val webOrigin = providers.gradleProperty("delfos.webOrigin").getOrElse("https://delfos.manuelalejandro.com")
val generateConfig = tasks.register("generateConfig") {
    // Local values: the action may not hold a reference to the script, for the configuration cache.
    val url = apiBaseUrl
    val origin = webOrigin
    val generated = layout.buildDirectory.dir("generated/config/commonMain/kotlin")
    inputs.property("apiBaseUrl", url)
    inputs.property("webOrigin", origin)
    outputs.dir(generated)
    doLast {
        val target = generated.get().asFile.resolve("com/manuelalejandro/delfos/mobile/Config.kt")
        target.parentFile.mkdirs()
        target.writeText(
            "package com.manuelalejandro.delfos.mobile\n\n" +
                "// Generated by the mobile build from Gradle properties; do not edit.\n" +
                "internal object Config {\n" +
                "    const val API_BASE_URL: String = \"$url\"\n" +
                "    const val WEB_ORIGIN: String = \"$origin\"\n" +
                "}\n",
        )
    }
}

